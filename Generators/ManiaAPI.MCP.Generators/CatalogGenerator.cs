    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var files = context.AdditionalTextsProvider
            .Select((file, token) => (file.Path, Text: file.GetText(token)?.ToString() ?? ""))
            .Collect();

        context.RegisterSourceOutput(context.CompilationProvider.Combine(files), (output, input) =>
        {
            Generate(output, input.Left, input.Right);
        });
    }

    private static void Generate(
        SourceProductionContext context,
        Compilation compilation,
        ImmutableArray<(string Path, string Text)> files)
    {
        var documentation = ReadDocumentation(files);
        var accountRules = ReadAccountRules(files);
        var roots = new HashSet<string>(StringComparer.Ordinal);

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine("#pragma warning disable CS0618 // Obsolete operations remain discoverable, ranked last.");
        source.AppendLine("namespace ManiaAPI.MCP.Catalog;");
        source.AppendLine();
        source.AppendLine("public static class GeneratedCatalog");
        source.AppendLine("{");
        source.AppendLine("    public static Operation[] Create() => new Operation[]");
        source.AppendLine("    {");

        foreach (var client in Clients)
        {
            var type = compilation.GetTypeByMetadataName(client.Type);

            if (type is null)
            {
                continue;
            }

            var groups = type.AllInterfaces.Reverse().Append(type).SelectMany(item => item.GetMembers())
                .OfType<IMethodSymbol>()
                .Where(method => IsCatalogOperation(method, client.Prefix))
                .GroupBy(method => method.ToDisplayString(), StringComparer.Ordinal)
                .Select(group => group.First())
                .OrderBy(method => method.ToDisplayString(), StringComparer.Ordinal)
                .GroupBy(method => method.Name)
                .ToArray();

            var timed = TimedVariants(groups);

            foreach (var group in groups)
            {
                if (timed.Skipped.Contains(group.Key))
                {
                    continue;
                }

                var overloads = SelectOverloads(group);

                if (overloads.Length == 0)
                {
                    continue;
                }

                var id = client.Prefix + "." + Snake(group.Key);
                var comments = Comments(documentation, type, overloads);
                var summary = Summarize(comments.OrderByDescending(comment => comment.Length).FirstOrDefault() ?? "", group.Key);
                var obsolete = overloads.All(method => method.GetAttributes()
                    .Any(attribute => attribute.AttributeClass?.Name == "ObsoleteAttribute"));

                if (timed.Variants.TryGetValue(group.Key, out var variants))
                {
                    // Call the timed variant wherever one takes the same parameters. The summary stays the plain
                    // method's; the variant's documentation still helps describe the parameters.
                    overloads = overloads.Select(method => variants.FirstOrDefault(variant => SameParameters(method, variant)) ?? method).ToArray();
                    comments.AddRange(Comments(documentation, type, variants));
                }

                var readOnly = IsRead(methodName: group.Key);
                var playerOnly = IsPlayerOperation(client.Prefix, group.Key);
                var requires = playerOnly ? "oauth" : client.Requires;
                var provider = client.Prefix == "trackmania.api" ? "trackmania" :
                    client.Prefix == "maniaplanet.web" ? "maniaplanet" : null;
                var serviceOnly = !readOnly || (accountRules.TryGetValue(id, out var rule)
                    ? rule == "service"
                    : summary.IndexOf("service account", StringComparison.OrdinalIgnoreCase) >= 0);

                serviceOnly = client.Requires == "nadeo" && serviceOnly;

                source.AppendLine("        new Operation(");
                source.AppendLine($"            {Literal(id)},");
                source.AppendLine($"            {Literal(client.Toolset)},");
                source.AppendLine($"            {Literal(summary)},");
                source.AppendLine($"            {Literal(requires)},");
                source.AppendLine($"            {(client.Exchange is null ? "null" : Literal(client.Exchange))},");
                source.AppendLine($"            {(serviceOnly ? "true" : "false")},");
                source.AppendLine($"            {(obsolete ? "true" : "false")},");
                source.AppendLine("            new OperationOverload[]");
                source.AppendLine("            {");

                foreach (var method in overloads)
                {
                    WriteOverload(source, roots, type, client.Prefix, method, comments);
                }

                var binary = overloads.Any(method => IsBinary(ResultType(method)));

                source.AppendLine("            })");
                source.AppendLine("        {");
                source.AppendLine($"            ReadOnly = {(readOnly ? "true" : "false")},");
                source.AppendLine($"            ReturnsBinary = {(binary ? "true" : "false")},");
                source.AppendLine($"            Idempotent = {(readOnly || group.Key.StartsWith("Set", StringComparison.Ordinal) || group.Key.StartsWith("Remove", StringComparison.Ordinal) ? "true" : "false")},");
                source.AppendLine($"            PlatformClient = {(client.Prefix == "masterserver.tmt" ? Literal("tmt") : "null")},");
                source.AppendLine($"            PlayerOnly = {(playerOnly ? "true" : "false")},");
                source.AppendLine($"            OAuthProvider = {(provider is null ? "null" : Literal(provider))},");
                source.AppendLine($"            OAuthScopes = new string[] {{ {string.Join(", ", RequiredScopes(client.Prefix, group.Key).Select(Literal))} }}");
                source.AppendLine("        },");
            }
        }

        source.AppendLine("    };");
        source.AppendLine("}");

        context.AddSource("OperationCatalog.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        ValidateJsonRoots(context, compilation, roots);
    }

    /// <summary>
    /// MasterServer clients pair <c>GetXAsync</c> with <c>GetXResponseAsync</c>, which returns the same result
    /// with the execution, parse, and request times (<c>MasterServerResponse</c>), or, for aggregated Trackmania
    /// Turbo, with those times and any error per platform. The operation keeps the plain ID but calls the
    /// response variant, so that information comes along and the catalog has one entry.
    /// </summary>
    private static (HashSet<string> Skipped, Dictionary<string, IMethodSymbol[]> Variants) TimedVariants(IGrouping<string, IMethodSymbol>[] groups)
    {
        var names = new HashSet<string>(groups.Select(group => group.Key), StringComparer.Ordinal);
        var skipped = new HashSet<string>(StringComparer.Ordinal);
        var variants = new Dictionary<string, IMethodSymbol[]>(StringComparer.Ordinal);

        foreach (var group in groups)
        {
            if (!group.Key.EndsWith("ResponseAsync", StringComparison.Ordinal) ||
                !group.All(method => ResultType(method) is { } result && !IsBinary(result) &&
                    result.ContainingNamespace?.ToDisplayString().StartsWith("ManiaAPI.MasterServer", StringComparison.Ordinal) == true))
            {
                continue;
            }

            var plain = group.Key.Substring(0, group.Key.Length - "ResponseAsync".Length) + "Async";

            if (names.Contains(plain))
            {
                skipped.Add(group.Key);
                variants[plain] = group.ToArray();
            }
        }

        return (skipped, variants);
    }

    private static bool SameParameters(IMethodSymbol left, IMethodSymbol right)
    {
        var a = left.Parameters.Where(parameter => !IsInjected(parameter)).ToArray();
        var b = right.Parameters.Where(parameter => !IsInjected(parameter)).ToArray();

        return a.Length == b.Length && a.Zip(b, (x, y) => x.Name == y.Name &&
            SymbolEqualityComparer.Default.Equals(x.Type.WithNullableAnnotation(NullableAnnotation.None), y.Type.WithNullableAnnotation(NullableAnnotation.None))).All(same => same);
    }

    private static bool IsCatalogOperation(IMethodSymbol method, string prefix)
    {
        if (method.MethodKind != MethodKind.Ordinary || method.IsGenericMethod || method.IsStatic)
        {
            return false;
        }

        if (method.Name is "Dispose" or "DisposeAsync" or "AuthorizeAsync" or "RefreshAsync" or "AuthenticateAsync" or "SendAsync" ||
            method.Name == "GetAccountDisplayNamesAsync" || method.Name.Contains("Password"))
        {
            return false;
        }

        if (method.Parameters.Any(parameter => parameter.Type.Name == "HttpMethod"))
        {
            return false;
        }

        return method.ReturnType.Name == "Task" || IsRead(method.Name);
    }

    private static bool IsPlayerOperation(string prefix, string name)
    {
        return prefix == "trackmania.api" && (name.Contains("User") || name.Contains("Favorite")) ||
            prefix == "maniaplanet.web" && name is "GetDedicatedAccountsAsync" or "GetEmailAsync" or
                "GetMapsAsync" or "GetPlayerAsync" or "GetTitlesAsync";
    }

    private static string[] RequiredScopes(string prefix, string name)
    {
        if (prefix == "trackmania.api")
        {
            return name switch
            {
                "GetUserAdminClubsAsync" => ["clubs"],
                "GetUserFavoriteMapsAsync" => ["read_favorite"],
                "AddUserFavoriteMapAsync" or "RemoveUserFavoriteMapAsync" => ["write_favorite"],
                _ => []
            };
        }

        return prefix == "maniaplanet.web" ? name switch
        {
            "GetEmailAsync" => ["email"],
            "GetDedicatedAccountsAsync" => ["dedicated"],
            "GetMapsAsync" => ["maps"],
            "GetTitlesAsync" => ["titles"],
            "GetPlayerAsync" => ["basic"],
            _ => []
        } : [];
    }

    private static bool IsRead(string methodName)
    {
        return new[] { "Get", "Search", "Check", "Download", "Fetch", "Test", "Ping" }
            .Any(prefix => methodName.StartsWith(prefix, StringComparison.Ordinal));
    }

    private static ITypeSymbol? ResultType(IMethodSymbol method)
    {
        return method.ReturnType is INamedTypeSymbol { Name: "Task" } task
            ? task.TypeArguments.FirstOrDefault()
            : method.ReturnType;
    }

    private static bool IsBinary(ITypeSymbol? type)
    {
        return type?.ToDisplayString() is "System.Net.Http.HttpResponseMessage" or "System.IO.Stream" ||
            type?.ContainingNamespace?.ToDisplayString() == "TmScores";
    }

    private static IMethodSymbol[] SelectOverloads(IEnumerable<IMethodSymbol> group)
    {
        var methods = group.ToArray();

        return methods
            .Where(method => methods.Length == 1 || !method.Parameters.Any(parameter => parameter.IsParams))
            .Where(method => !method.Parameters.Any(parameter =>
                parameter.Type.Name.EndsWith("Item", StringComparison.Ordinal) || parameter.Type.Name == "ReplayItemMX"))
            .OrderByDescending(method => method.Parameters.Count(parameter => parameter.IsOptional))
            .ThenByDescending(method => method.Parameters.Length)
            .ToArray();
    }

    private static void WriteOverload(
        StringBuilder source,
        HashSet<string> roots,
        INamedTypeSymbol clientType,
        string prefix,
        IMethodSymbol method,
        IReadOnlyList<string> comments)
    {
        var parameters = method.Parameters.Where(parameter => !IsInjected(parameter)).ToArray();
        var isTask = method.ReturnType is INamedTypeSymbol task && task.Name == "Task";
        var resultType = ResultType(method);
        var binary = IsBinary(resultType);
        var signature = string.Join(", ", parameters.Select(ParameterSignature));

        source.AppendLine("                new OperationOverload(");
        source.Append("                    CatalogMetadata.Input(");

        for (var i = 0; i < parameters.Length; i++)
        {
            var parameter = parameters[i];
            var parameterType = TypeName(parameter.Type);
            roots.Add(parameterType);

            var description = ParameterDescription(comments, parameter.Name);
            var defaultValue = parameter.HasExplicitDefaultValue && parameter.ExplicitDefaultValue is not null
                ? ", true, " + Default(parameter)
                : "";

            source.AppendLine(i == 0 ? "" : ",");
            source.Append($"                        ({Literal(parameter.Name)}, CatalogMetadata.Parameter<{parameterType}>(");
            source.Append($"{Literal(parameter.Name)}, {(description is null ? "null" : Literal(description))}{defaultValue}), ");
            source.Append(parameter.IsOptional ? "false)" : "true)");
        }

        source.AppendLine("),");
        source.AppendLine($"                    {Literal(signature)},");

        if (binary || resultType is null)
        {
            source.AppendLine("                    System.Text.Json.Nodes.JsonNode.Parse(\"{\\\"type\\\":\\\"object\\\"}\")!,");
        }
        else
        {
            roots.Add(TypeName(resultType!));
            source.AppendLine($"                    CatalogMetadata.Schema<{TypeName(resultType!)}>(),");
        }

        source.AppendLine("                    async (context, arguments, cancellationToken) =>");
        source.AppendLine("                    {");

        if (resultType?.ContainingNamespace?.ToDisplayString() == "TmScores")
        {
            source.AppendLine($"                        return await context.ScoresAsync({Literal(prefix)}, {Literal(method.Name)}, arguments, cancellationToken);");
            source.AppendLine("                    }),");
            return;
        }

        source.Append(resultType is null ? "                        " :
            binary && resultType.Name is "HttpResponseMessage" or "Stream" ? "                        using var result = " : "                        var result = ");
        source.Append(isTask ? "await " : "");
        var boundClient = TypeName(clientType).Replace(".IMasterServerTMUF", ".MasterServerTMUF");
        source.AppendLine($"(await context.ClientAsync<{boundClient}>({Literal(prefix)}, cancellationToken)).{method.Name}(");

        for (var i = 0; i < method.Parameters.Length; i++)
        {
            var parameter = method.Parameters[i];
            var argument = IsInjected(parameter)
                ? parameter.Type.Name == "CancellationToken" ? "cancellationToken" : "null"
                : $"CatalogMetadata.Argument<{TypeName(parameter.Type)}>(arguments, {Literal(parameter.Name)}, {Default(parameter)})";

            source.Append("                            " + argument);
            source.AppendLine(i == method.Parameters.Length - 1 ? "" : ",");
        }

        source.AppendLine("                        );");
        source.AppendLine();
        source.AppendLine(resultType is null
            ? "                        return new System.Text.Json.Nodes.JsonObject { [\"completed\"] = true };"
            : binary
                ? resultType.Name is "HttpResponseMessage" or "Stream"
                    ? "                        return await context.BinaryAsync(result, cancellationToken);"
                    : "                        return context.BinarySummary();"
                : "                        return CatalogMetadata.Result(result);");
        source.AppendLine("                    }),");
    }

    private static bool IsInjected(IParameterSymbol parameter)
    {
        return parameter.Type.Name == "CancellationToken" ||
            parameter.Type is INamedTypeSymbol { Name: "IProgress", Arity: 1 };
    }

    /// <summary>
    /// A compact signature for search results, like <c>mapUid: string, zoneId?: guid, length?: int = 10</c>.
    /// </summary>
    private static string ParameterSignature(IParameterSymbol parameter)
    {
        var optional = parameter.IsOptional ? "?" : "";
        var fallback = parameter.HasExplicitDefaultValue
            ? " = " + (parameter.ExplicitDefaultValue switch
            {
                null => "null",
                string text => Literal(text),
                var value when Underlying(parameter.Type).TypeKind == TypeKind.Enum => Underlying(parameter.Type).GetMembers()
                    .OfType<IFieldSymbol>().FirstOrDefault(field => field.HasConstantValue && Equals(field.ConstantValue, value))?.Name
                    ?? Convert.ToString(value, CultureInfo.InvariantCulture),
                var value => Convert.ToString(value, CultureInfo.InvariantCulture)?.ToLowerInvariant()
            })
            : "";

        return parameter.Name + optional + ": " + CompactType(parameter.Type) + fallback;
    }

    private static ITypeSymbol Underlying(ITypeSymbol type)
    {
        return type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable
            ? nullable.TypeArguments[0]
            : type;
    }

    private static string CompactType(ITypeSymbol type)
    {
        type = Underlying(type);

        if (type is IArrayTypeSymbol array)
        {
            return CompactType(array.ElementType) + "[]";
        }

        if (type.SpecialType == SpecialType.System_String)
        {
            return "string";
        }

        if (type is INamedTypeSymbol { IsGenericType: true, TypeArguments.Length: 1 } collection &&
            collection.AllInterfaces.Append(collection).Any(item =>
                item.OriginalDefinition.SpecialType == SpecialType.System_Collections_Generic_IEnumerable_T))
        {
            return CompactType(collection.TypeArguments[0]) + "[]";
        }

        if (type.TypeKind == TypeKind.Enum)
        {
            var members = type.GetMembers().OfType<IFieldSymbol>().Where(field => field.HasConstantValue).Select(field => field.Name).ToArray();

            return members.Length is > 0 and <= 6 ? string.Join("|", members) : type.Name;
        }

        return type.ToDisplayString() switch
        {
            "System.Guid" => "guid",
            "System.DateTimeOffset" or "System.DateTime" => "datetime",
            "System.TimeSpan" => "timespan",
            "System.Uri" => "url",
            _ when type.SpecialType != SpecialType.None => type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat),
            _ => type.Name
        };
    }

    /// <summary>
    /// The documentation comments of an operation: from the client interface, the interface that declares
    /// each overload, and the implementing class, so <c>&lt;param&gt;</c> text is found wherever it was written.
    /// </summary>
    private static List<string> Comments(Dictionary<string, List<string>> documentation, INamedTypeSymbol type, IMethodSymbol[] overloads)
    {
        var keys = overloads.Select(method => method.ContainingType.Name + "." + method.Name)
            .Prepend(type.Name + "." + overloads[0].Name)
            .Distinct(StringComparer.Ordinal);

        return keys.SelectMany(key => documentation.TryGetValue(key, out var comments) ? comments : [])
            .Concat(overloads.Select(method => method.GetDocumentationCommentXml() ?? ""))
            .Where(comment => comment.Length > 0)
            .ToList();
    }

    private static string? ParameterDescription(IReadOnlyList<string> comments, string name)
    {
        foreach (var comment in comments)
        {
            var match = Regex.Match(comment, "<param\\s+name=\"" + Regex.Escape(name) + "\"\\s*>(.*?)</param>", RegexOptions.Singleline);
            var text = Regex.Replace(Regex.Replace(match.Groups[1].Value, "<[^>]+>", " ").Replace("///", " "), @"\s+", " ").Trim();

            if (text.Length > 0)
            {
                return text;
            }
        }

        return null;
    }

    private static Dictionary<string, List<string>> ReadDocumentation(ImmutableArray<(string Path, string Text)> files)
    {
        var documentation = new Dictionary<string, List<string>>(StringComparer.Ordinal);

        foreach (var file in files.Where(file => file.Path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase)))
        {
            var tree = CSharpSyntaxTree.ParseText(file.Text);

            foreach (var declaration in tree.GetRoot().DescendantNodes().OfType<TypeDeclarationSyntax>())
            {
                // A class's comments also count for its interface (MasterServerTMUF for IMasterServerTMUF).
                var names = declaration is InterfaceDeclarationSyntax
                    ? new[] { declaration.Identifier.ValueText }
                    : new[] { declaration.Identifier.ValueText, "I" + declaration.Identifier.ValueText };

                foreach (var method in declaration.Members.OfType<MethodDeclarationSyntax>())
                {
                    var comment = method.GetLeadingTrivia().ToFullString();

                    if (comment.IndexOf("///", StringComparison.Ordinal) < 0)
                    {
                        continue;
                    }

                    foreach (var name in names)
                    {
                        var key = name + "." + method.Identifier.ValueText;

                        if (!documentation.TryGetValue(key, out var comments))
                        {
                            documentation[key] = comments = [];
                        }

                        comments.Add(comment);
                    }
                }
            }
        }

        return documentation;
    }

    private static Dictionary<string, string> ReadAccountRules(ImmutableArray<(string Path, string Text)> files)
    {
        var rules = new Dictionary<string, string>(StringComparer.Ordinal);

        foreach (var file in files.Where(file => file.Path.EndsWith(".accounts", StringComparison.Ordinal)))
        {
            foreach (var line in file.Text.Split('\n'))
            {
                var columns = line.Trim().Split('|');

                if (columns.Length == 2 && !columns[0].StartsWith("#", StringComparison.Ordinal))
                {
                    rules[columns[0].Trim()] = columns[1].Trim();
                }
            }
        }

        return rules;
    }

    private static void ValidateJsonRoots(SourceProductionContext context, Compilation compilation, HashSet<string> roots)
    {
        // Generators cannot consume each other's output. JSON attributes must be in ordinary source.
        var jsonContext = compilation.GetTypeByMetadataName("ManiaAPI.MCP.Serialization.CatalogJsonContext");

        if (jsonContext is null)
        {
            return;
        }

        var registered = new HashSet<string>(jsonContext.GetAttributes()
            .Where(attribute => attribute.AttributeClass?.Name == "JsonSerializableAttribute")
            .Select(attribute => attribute.ConstructorArguments.FirstOrDefault().Value)
            .OfType<ITypeSymbol>()
            .Select(TypeName));

        foreach (var root in roots.OrderBy(value => value, StringComparer.Ordinal))
        {
            if (!registered.Contains(root))
            {
                context.ReportDiagnostic(Diagnostic.Create(MissingMetadata, Location.None, root));
            }
        }
    }

    private static string TypeName(ITypeSymbol type)
    {
        var format = SymbolDisplayFormat.FullyQualifiedFormat.WithMiscellaneousOptions(
            SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers |
            SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

        return type.WithNullableAnnotation(NullableAnnotation.None).ToDisplayString(format);
    }

    private static string Literal(string value)
    {
        return SymbolDisplay.FormatLiteral(value, quote: true);
    }

    private static string Default(IParameterSymbol parameter)
    {
        if (!parameter.HasExplicitDefaultValue || parameter.ExplicitDefaultValue is null)
        {
            return "default!";
        }

        return parameter.ExplicitDefaultValue switch
        {
            string value => Literal(value),
            bool value => value ? "true" : "false",
            // The value is parenthesized: "(Enum)-1" would parse as a subtraction.
            var value => "(" + TypeName(parameter.Type) + ")(" + Convert.ToString(value, CultureInfo.InvariantCulture) + ")"
        };
    }

    private static string Snake(string name)
    {
        if (name.StartsWith("Get", StringComparison.Ordinal))
        {
            name = name.Substring(3);
        }

        if (name.EndsWith("Async", StringComparison.Ordinal))
        {
            name = name.Substring(0, name.Length - 5);
        }

        var words = Regex.Replace(name, "([A-Z]+)([A-Z][a-z])", "$1_$2");

        return Regex.Replace(words, "([a-z0-9])([A-Z])", "$1_$2").ToLowerInvariant();
    }

    private static string Summarize(string documentation, string methodName)
    {
        var match = Regex.Match(documentation, @"<summary>(.*?)</summary>", RegexOptions.Singleline);
        var text = Regex.Replace(match.Value, "<[^>]+>", " ").Replace("///", " ");
        var summary = Regex.Replace(text, @"\s+", " ").Trim();

        return summary.Length == 0 ? Snake(methodName).Replace('_', ' ') + "." : summary;
    }
